// 한국 공휴일은 설날/추석처럼 음력 기반이라 공식이 없고, 매년 정부 발표(월력요항)로만
// 확정된다 — 그래서 연도별로 수동으로 갱신해야 한다. 여기 없는 연도는 공휴일 스킵이
// 적용되지 않으니(평일 발송), 매년 말에 다음 해 목록을 추가해줄 것.
const KR_HOLIDAYS = new Set([
  // 2026
  '2026-01-01', // 신정
  '2026-02-16', // 설날 연휴
  '2026-02-17', // 설날
  '2026-02-18', // 설날 연휴
  '2026-03-02', // 삼일절 대체공휴일 (3/1이 일요일)
  '2026-05-05', // 어린이날
  '2026-05-25', // 부처님오신날 대체공휴일 (5/24가 일요일)
  '2026-07-17', // 제헌절 (2026년부터 18년 만에 공휴일로 재지정)
  '2026-08-17', // 광복절 대체공휴일 (8/15가 토요일)
  '2026-09-24', // 추석 연휴
  '2026-09-25', // 추석
  '2026-10-05', // 개천절 대체공휴일 (10/3이 토요일)
  '2026-10-09', // 한글날
  '2026-12-25' // 성탄절
]);

export function isHoliday(issueDate) {
  return KR_HOLIDAYS.has(issueDate);
}
